public class MapGenerator : MonoBehaviour
{
    // 壁Prefab
    public GameObject Wall;

    //プレイヤーPrefab
    public GameObject Player_Tank;

    //敵のPrefab
    public GameObject Enemy;

    // マップデータ
    string[] map =
 {
    "########################################",
    "#......................................#",
    "#.................E....................#",
    "#......................................#",
    "#.................E....................#",
    "#......................................#",
    "#.................E....................#",
    "#......................................#",
