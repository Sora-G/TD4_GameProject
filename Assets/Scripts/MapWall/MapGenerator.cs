    "#......................................#",
    "#...................E..................#",
    "#......................................#",
    "#......................................#",
    "#......................................#",
    "#......................................#",
    "#......................................#",
    "#......................................#",
    "#......................................#",
    "#...........E..........................#",
    "#......................................#",
    "#......................................#",
