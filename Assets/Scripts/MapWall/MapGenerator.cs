    "########################################",
};



    void Start()
    {
        GenerateMap();
    }

    [ContextMenu("Generate Map")]

    void GenerateMap()
    {
        ClearMap();

        for (int z = 0; z < map.Length; z++)
        {
            for (int x = 0; x < map[z].Length; x++)
            {
                char chip = map[z][x];

                Vector3 pos = new Vector3(x, 1, z);

                switch (chip)
                {
                    // 壁
                    case '#':
                        Instantiate(
                            Wall,
                            pos,
                            Quaternion.identity,
                            transform
                        );
                        break;

                    // プレイヤー
                    case 'P':
                        Instantiate(
                            Player_Tank,
                            pos,
                            Quaternion.identity,
                            transform
                        );
                        break;

                    // 敵
                    case 'E':
                        Instantiate(
                            Enemy,
                            pos,
                            Quaternion.identity,
                            transform
                        );
                        break;
                }
            }
        }
    }

    [ContextMenu("Clear Map")]

    void ClearMap()
    {
        while (transform.childCount > 0)
        {
            DestroyImmediate(transform.GetChild(0).gameObject);
        }
    }
}