    void GenerateMap()
    {
        // 縦
        for (int z = 0; z < map.GetLength(0); z++)
        {
            // 横
            for (int x = 0; x < map.GetLength(1); x++)
            {
                // 1なら壁生成
                if (map[z, x] == 1)
                {
                    Instantiate(
                        Wall,
                        new Vector3(x, 1, z),
                        Quaternion.identity
                    );
                }

                // 2ならプレイヤー生成
                if (map[z, x] == 2)
                {
                    Instantiate(
                        Player_Tank,
                        new Vector3(x, 1, z),
